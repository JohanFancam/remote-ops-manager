import React, { useState, useEffect, useRef, useMemo } from 'react';
import { useQuery, useQueryClient } from '@tanstack/react-query';
import { base44 } from '@/api/base44Client';
import { useApp } from '../components/AppContext';
import { getDisplayName } from '../components/utils/nameUtils';
import ManageUsersSection from '../components/settings/ManageUsersSection';
import AutoAssignSettings from '../components/settings/AutoAssignSettings';
import TimezoneSettings from '../components/settings/TimezoneSettings';
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { Badge } from "@/components/ui/badge";
import {
  Users, UserPlus, User, Trash2, RefreshCw, Phone, PhoneOff,
  MessageSquare, Save, Image, Send, X, DollarSign, Edit2
} from 'lucide-react';

function MessageTemplatesSection({ appSettings, queryClient }) {
  const defaultRigs = 'Rigs ready for today: {list}';
  const defaultOk = '{name} complete, no issues to report.';
  const defaultIssues = '{name} complete — ⚠️ Issues reported: {notes}';

  const [rigsTemplate, setRigsTemplate] = React.useState('');
  const [summaryOk, setSummaryOk] = React.useState('');
  const [summaryIssues, setSummaryIssues] = React.useState('');
  const [saved, setSaved] = React.useState(false);

  React.useEffect(() => {
    if (!appSettings.length) return;
    setRigsTemplate(appSettings.find(s => s.key === 'rigscheck_template')?.value || defaultRigs);
    setSummaryOk(appSettings.find(s => s.key === 'summary_template_ok')?.value || defaultOk);
    setSummaryIssues(appSettings.find(s => s.key === 'summary_template_issues')?.value || defaultIssues);
  }, [appSettings]);

  const handleSave = async () => {
    const pairs = [
      { key: 'rigscheck_template', value: rigsTemplate, description: 'Rigs check message template' },
      { key: 'summary_template_ok', value: summaryOk, description: 'Shoot summary — no issues template' },
      { key: 'summary_template_issues', value: summaryIssues, description: 'Shoot summary — issues template' },
    ];
    for (const pair of pairs) {
      const existing = appSettings.find(s => s.key === pair.key);
      if (existing) {
        await base44.entities.AppSettings.update(existing.id, { value: pair.value });
      } else {
        await base44.entities.AppSettings.create(pair);
      }
    }
    setSaved(true);
    setTimeout(() => setSaved(false), 2000);
    queryClient.invalidateQueries({ queryKey: ['appSettings'] });
  };

  return (
    <Card className="bg-gray-900 border-gray-800 mb-6">
      <CardHeader className="border-b border-gray-800 pb-4">
        <CardTitle className="text-white flex items-center gap-2">
          <MessageSquare className="h-5 w-5 text-blue-400" /> Message Templates
        </CardTitle>
      </CardHeader>
      <CardContent className="pt-4 space-y-4">
        <p className="text-xs text-gray-500">
          Customise the messages generated by the Rigs Check and Shoot Summary panels.
        </p>

        <div>
          <label className="text-xs text-gray-400 block mb-1">
            Rigs Check message — use <code className="text-blue-400">{'{list}'}</code> for the shoot list
          </label>
          <Input
            value={rigsTemplate}
            onChange={e => setRigsTemplate(e.target.value)}
            placeholder={defaultRigs}
            className="bg-gray-800 border-gray-700 text-white placeholder:text-gray-600 text-sm"
          />
          <p className="text-xs text-gray-600 mt-1">
            Example output: <span className="text-gray-400 italic">Rigs ready for today: Nationals (Data/Fancam), Lightning (Data/Fancam/Sound)</span>
          </p>
        </div>

        <div>
          <label className="text-xs text-gray-400 block mb-1">
            Shoot Summary — no issues — use <code className="text-blue-400">{'{name}'}</code> for shoot name
          </label>
          <Input
            value={summaryOk}
            onChange={e => setSummaryOk(e.target.value)}
            placeholder={defaultOk}
            className="bg-gray-800 border-gray-700 text-white placeholder:text-gray-600 text-sm"
          />
        </div>

        <div>
          <label className="text-xs text-gray-400 block mb-1">
            Shoot Summary — issues reported — use <code className="text-blue-400">{'{name}'}</code> and <code className="text-blue-400">{'{notes}'}</code>
          </label>
          <Input
            value={summaryIssues}
            onChange={e => setSummaryIssues(e.target.value)}
            placeholder={defaultIssues}
            className="bg-gray-800 border-gray-700 text-white placeholder:text-gray-600 text-sm"
          />
        </div>

        <Button onClick={handleSave} className="bg-blue-700 hover:bg-blue-600 gap-2">
          <Save className="h-4 w-4" /> {saved ? '✓ Saved!' : 'Save Templates'}
        </Button>
      </CardContent>
    </Card>
  );
}



const SLACK_PHASES = [
  { key: 'setup_complete', label: 'Setup Complete', placeholder: 'Setup complete — {team} shoot ready to go!' },
  { key: 'pre_shoot_started', label: 'Pre-Shoot Started', placeholder: 'Pre-shoot started — {team}' },
  { key: 'attention_started', label: 'Attention Started', placeholder: 'Attention phase started — {team}' },
  { key: 'sound_started', label: 'Sound Started', placeholder: 'Sound check in progress — {team}' },
];

export default function Settings() {
  const { user, isAdmin, isStandby, isAccounts, effectiveRole } = useApp();
  const queryClient = useQueryClient();

  const [slackMsgs, setSlackMsgs] = useState({});
  const [slackSaved, setSlackSaved] = useState(false);
  const [standbyDone, setStandbyDone] = useState(false);
  const [rateBaseInput, setRateBaseInput] = useState('');
  const [adminDayHoursInput, setAdminDayHoursInput] = useState('9.5');
  const [rateAdditionalInput, setRateAdditionalInput] = useState('');
  const [rateStandbyInput, setRateStandbyInput] = useState('');
  const [ratePostponedInput, setRatePostponedInput] = useState('');
  const [ratesSaved, setRatesSaved] = useState(false);

  // Logo
  const [logoUploading, setLogoUploading] = useState(false);
  const logoInputRef = useRef();

  const { data: appSettings = [] } = useQuery({
    queryKey: ['appSettings'],
    queryFn: () => base44.entities.AppSettings.list(),
  });

  const { data: rawUsers = [] } = useQuery({
    queryKey: ['allUsers'],
    queryFn: () => base44.entities.User.list(),
    enabled: isAdmin,
  });

  const { data: pendingUsers = [] } = useQuery({
    queryKey: ['pendingUsers'],
    queryFn: () => base44.entities.PendingUser.list(),
    enabled: isAdmin,
  });

  // Merge PendingUser (admin-defined names/roles) with User entity records
  const allUsers = useMemo(() => {
    const map = new Map();
    pendingUsers.forEach(pu => {
      const email = pu.email?.trim().toLowerCase();
      if (!email) return;
      map.set(email, { email, full_name: pu.full_name || '', role: pu.role || 'user', inactive: pu.inactive || false });
    });
    rawUsers.forEach(u => {
      const email = u.email?.trim().toLowerCase();
      if (!email) return;
      const existing = map.get(email);
      // Use PendingUser role only if it's a non-empty string; otherwise fall back to User entity role
      const resolvedRole = (existing?.role && existing.role !== '') ? existing.role : (u.role || 'user');
      map.set(email, { ...u, email, full_name: existing?.full_name || u.full_name || '', role: resolvedRole, inactive: existing?.inactive || false });
    });
    return Array.from(map.values());
  }, [rawUsers, pendingUsers]);



  const logoSetting = appSettings.find(s => s.key === 'app_logo_url');
  const logoUrl = logoSetting?.value;

  useEffect(() => {
    if (!appSettings.length) return;
    const msgs = {};
    SLACK_PHASES.forEach(p => {
      const setting = appSettings.find(s => s.key === `slack_${p.key}`);
      if (setting) msgs[p.key] = setting.value;
    });
    setSlackMsgs(msgs);
    const br = appSettings.find(s => s.key === 'base_rate')?.value;
    const ar = appSettings.find(s => s.key === 'additional_rate')?.value;
    const sr = appSettings.find(s => s.key === 'standby_rate')?.value;
    const pr = appSettings.find(s => s.key === 'postponed_rate')?.value;
    if (br) setRateBaseInput(br);
    if (ar) setRateAdditionalInput(ar);
    if (sr) setRateStandbyInput(sr);
    if (pr) setRatePostponedInput(pr);
    const adh = appSettings.find(s => s.key === 'admin_day_hours')?.value;
    if (adh) setAdminDayHoursInput(adh);
  }, [appSettings]);

  const refresh = () => {
    queryClient.invalidateQueries({ queryKey: ['allUsers'] });
    queryClient.invalidateQueries({ queryKey: ['appSettings'] });
  };

  const handleStandbyToggle = async () => {
    const current = user?.standby || false;
    await base44.auth.updateMe({ standby: !current });
    setStandbyDone(true);
    setTimeout(() => setStandbyDone(false), 2000);
    queryClient.invalidateQueries({ queryKey: ['currentUser'] });
  };

  const handleSaveRates = async () => {
    const pairs = [
      { key: 'base_rate', value: rateBaseInput || '1000', description: 'Standard shoot rate (ZAR)' },
      { key: 'additional_rate', value: rateAdditionalInput || '250', description: 'Additional shoot rate (ZAR)' },
      { key: 'standby_rate', value: rateStandbyInput || '500', description: 'Flat standby day rate for Operator/Standby users (ZAR)' },
      { key: 'postponed_rate', value: ratePostponedInput || '200', description: 'Flat rate paid for a postponed shoot (ZAR)' },
      { key: 'admin_day_hours', value: adminDayHoursInput || '9.5', description: 'Admin working hours per active day (shoots/standby)' },
    ];
    for (const pair of pairs) {
      const existing = appSettings.find(s => s.key === pair.key);
      if (existing) {
        await base44.entities.AppSettings.update(existing.id, { value: pair.value });
      } else {
        await base44.entities.AppSettings.create(pair);
      }
    }
    setRatesSaved(true);
    setTimeout(() => setRatesSaved(false), 2000);
    queryClient.invalidateQueries({ queryKey: ['appSettings'] });
  };

  const handleSaveSlackMessages = async () => {
    for (const phase of SLACK_PHASES) {
      if (slackMsgs[phase.key] !== undefined) {
        const existing = appSettings.find(s => s.key === `slack_${phase.key}`);
        if (existing) {
          await base44.entities.AppSettings.update(existing.id, { value: slackMsgs[phase.key] });
        } else {
          await base44.entities.AppSettings.create({ key: `slack_${phase.key}`, value: slackMsgs[phase.key] });
        }
      }
    }
    setSlackSaved(true);
    setTimeout(() => setSlackSaved(false), 2000);
    queryClient.invalidateQueries({ queryKey: ['appSettings'] });
  };

  const handleLogoUpload = async (e) => {
    const file = e.target.files?.[0];
    if (!file) return;
    setLogoUploading(true);
    const { file_url } = await base44.integrations.Core.UploadFile({ file });
    if (logoSetting) {
      await base44.entities.AppSettings.update(logoSetting.id, { value: file_url });
    } else {
      await base44.entities.AppSettings.create({ key: 'app_logo_url', value: file_url, description: 'Custom app logo' });
    }
    setLogoUploading(false);
    queryClient.invalidateQueries({ queryKey: ['appSettings'] });
  };

  return (
    <div className="min-h-screen bg-gray-950 text-white p-4 md:p-6">
      <div className="max-w-4xl mx-auto">
        <div className="flex items-center justify-between mb-8">
          <h1 className="text-3xl font-bold">Settings</h1>
          <Button onClick={() => window.location.reload()} variant="outline" className="border-gray-700 text-gray-300 hover:bg-gray-800 gap-2">
            <RefreshCw className="h-4 w-4" /> Refresh App
          </Button>
        </div>

        {/* My Profile */}
        <Card className="bg-gray-900 border-gray-800 mb-6">
          <CardHeader className="border-b border-gray-800 pb-4">
            <CardTitle className="text-white flex items-center gap-2">
              <User className="h-5 w-5 text-blue-400" /> My Profile
            </CardTitle>
          </CardHeader>
          <CardContent className="pt-4">
            <div className="flex items-center gap-4 flex-wrap">
              <div className="w-14 h-14 bg-gray-800 rounded-full flex items-center justify-center text-2xl font-bold text-blue-400">
                {user?.full_name?.charAt(0) || user?.email?.charAt(0)?.toUpperCase() || 'U'}
              </div>
              <div className="flex-1 min-w-0">
                <p className="text-lg font-semibold text-white">{user?.full_name || 'Unnamed'}</p>
                <p className="text-gray-400 text-sm">{user?.email}</p>
                <Badge className={`mt-1 text-xs ${isAdmin ? 'bg-blue-500/20 text-blue-400 border-blue-500/30' : isStandby ? 'bg-yellow-500/20 text-yellow-400 border-yellow-500/30' : effectiveRole === 'operator_standby' ? 'bg-purple-500/20 text-purple-400 border-purple-500/30' : isAccounts ? 'bg-green-500/20 text-green-400 border-green-500/30' : 'bg-gray-700 text-gray-300 border-gray-600'}`}>
                {isAdmin ? 'Admin' : isStandby ? 'Standby User' : effectiveRole === 'operator_standby' ? 'Operator/Standby' : isAccounts ? 'Accounts' : 'Remote Operator'}
                </Badge>
              </div>
            </div>
          </CardContent>
        </Card>

        {/* Time Zone — all users */}
        <TimezoneSettings />

        {/* App Logo — Admin only */}
        {isAdmin && (
          <Card className="bg-gray-900 border-gray-800 mb-6">
            <CardHeader className="border-b border-gray-800 pb-4">
              <CardTitle className="text-white flex items-center gap-2">
                <Image className="h-5 w-5 text-blue-400" /> App Logo
              </CardTitle>
            </CardHeader>
            <CardContent className="pt-4">
              <div className="flex items-center gap-4 flex-wrap">
                <div className="w-16 h-16 bg-gray-800 rounded-xl flex items-center justify-center overflow-hidden border border-gray-700">
                  {logoUrl
                    ? <img src={logoUrl} alt="App Logo" className="w-full h-full object-contain" />
                    : <span className="text-2xl font-bold text-blue-400">R</span>
                  }
                </div>
                <div>
                  <p className="text-sm text-gray-300 mb-2">Upload a custom logo (PNG, JPG, SVG recommended)</p>
                  <input ref={logoInputRef} type="file" accept="image/*" className="hidden" onChange={handleLogoUpload} />
                  <Button size="sm" onClick={() => logoInputRef.current?.click()} disabled={logoUploading}
                    className="bg-blue-700 hover:bg-blue-600 gap-2">
                    <Image className="h-4 w-4" />
                    {logoUploading ? 'Uploading...' : 'Upload Logo'}
                  </Button>
                </div>
              </div>
            </CardContent>
          </Card>
        )}

        {/* Standby Toggle — Admin only */}
        {isAdmin && (
          <Card className="bg-gray-900 border-gray-800 mb-6">
            <CardHeader className="border-b border-gray-800 pb-4">
              <CardTitle className="text-white flex items-center gap-2">
                <Phone className="h-5 w-5 text-yellow-400" /> Standby Contact
              </CardTitle>
            </CardHeader>
            <CardContent className="pt-4">
              <p className="text-gray-400 text-sm mb-4">
                When on standby, your name will appear in operator shoot details as the contact person.
              </p>
              <div className="flex items-center gap-4">
                <div className={`flex items-center gap-2 px-4 py-2 rounded-lg border ${isStandby ? 'border-yellow-700 bg-yellow-950/30' : 'border-gray-700 bg-gray-800/40'}`}>
                  {isStandby ? <Phone className="h-4 w-4 text-yellow-400" /> : <PhoneOff className="h-4 w-4 text-gray-500" />}
                  <span className={isStandby ? 'text-yellow-300 font-medium text-sm' : 'text-gray-400 text-sm'}>
                    {isStandby ? 'On Standby' : 'Not on Standby'}
                  </span>
                </div>
                <Button
                  onClick={handleStandbyToggle}
                  className={isStandby ? 'bg-gray-700 hover:bg-gray-600' : 'bg-yellow-700 hover:bg-yellow-600'}
                  size="sm"
                >
                  {standbyDone ? '✓ Saved' : isStandby ? 'Go Off Standby' : 'Go On Standby'}
                </Button>
              </div>
            </CardContent>
          </Card>
        )}

        {/* Pay Rates — Admin only */}
        {isAdmin && (
          <Card className="bg-gray-900 border-gray-800 mb-6">
            <CardHeader className="border-b border-gray-800 pb-4">
              <CardTitle className="text-white flex items-center gap-2">
                <DollarSign className="h-5 w-5 text-green-400" /> Pay Rates (ZAR)
              </CardTitle>
            </CardHeader>
            <CardContent className="pt-4 space-y-4">
              <p className="text-xs text-gray-500">Additional shoots only apply when within 2 hours of a standard shoot on the same day.</p>
              <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                <div>
                  <label className="text-xs text-gray-400 block mb-1">Standard Shoot Rate (R)</label>
                  <Input
                    type="number"
                    value={rateBaseInput}
                    onChange={e => setRateBaseInput(e.target.value)}
                    placeholder="1000"
                    className="bg-gray-800 border-gray-700 text-white"
                  />
                </div>
                <div>
                  <label className="text-xs text-gray-400 block mb-1">Additional Shoot Rate (R)</label>
                  <Input
                    type="number"
                    value={rateAdditionalInput}
                    onChange={e => setRateAdditionalInput(e.target.value)}
                    placeholder="250"
                    className="bg-gray-800 border-gray-700 text-white"
                  />
                </div>
                <div>
                  <label className="text-xs text-gray-400 block mb-1">Standby Day Rate — Operator/Standby (R)</label>
                  <Input
                    type="number"
                    value={rateStandbyInput}
                    onChange={e => setRateStandbyInput(e.target.value)}
                    placeholder="500"
                    className="bg-gray-800 border-gray-700 text-white"
                  />
                  <p className="text-xs text-gray-600 mt-1">Flat rate paid per standby day to Operator/Standby users.</p>
                </div>
                <div>
                  <label className="text-xs text-gray-400 block mb-1">Postponed Shoot Rate (R)</label>
                  <Input
                    type="number"
                    value={ratePostponedInput}
                    onChange={e => setRatePostponedInput(e.target.value)}
                    placeholder="200"
                    className="bg-gray-800 border-gray-700 text-white"
                  />
                  <p className="text-xs text-gray-600 mt-1">Flat rate paid to the assigned operator when a shoot is postponed.</p>
                </div>
                <div>
                  <label className="text-xs text-gray-400 block mb-1">Admin Working Hours / Active Day</label>
                  <Input
                    type="number"
                    step="0.5"
                    value={adminDayHoursInput}
                    onChange={e => setAdminDayHoursInput(e.target.value)}
                    placeholder="9.5"
                    className="bg-gray-800 border-gray-700 text-white"
                  />
                  <p className="text-xs text-gray-600 mt-1">Hours counted per day with a shoot or standby (never doubled)</p>
                </div>
              </div>
              <Button onClick={handleSaveRates} className="bg-green-700 hover:bg-green-600 gap-2">
                <Save className="h-4 w-4" /> {ratesSaved ? '✓ Saved!' : 'Save Rates'}
              </Button>
            </CardContent>
          </Card>
        )}

        {/* Message Templates — Admin only */}
        {isAdmin && (
          <MessageTemplatesSection appSettings={appSettings} queryClient={queryClient} />
        )}

        {/* Slack Messages — Admin only */}
        {isAdmin && (
          <Card className="bg-gray-900 border-gray-800 mb-6">
            <CardHeader className="border-b border-gray-800 pb-4">
              <CardTitle className="text-white flex items-center gap-2">
                <MessageSquare className="h-5 w-5 text-green-400" /> Phase Slack Messages
              </CardTitle>
            </CardHeader>
            <CardContent className="pt-4 space-y-3">
              <p className="text-xs text-gray-500">Use <code className="text-blue-400">{'{team}'}</code> to insert the team/client name dynamically.</p>
              {SLACK_PHASES.map(phase => (
                <div key={phase.key}>
                  <label className="text-xs text-gray-400 block mb-1">{phase.label}</label>
                  <Input
                    placeholder={phase.placeholder}
                    value={slackMsgs[phase.key] || ''}
                    onChange={e => setSlackMsgs({ ...slackMsgs, [phase.key]: e.target.value })}
                    className="bg-gray-800 border-gray-700 text-white placeholder:text-gray-600 text-sm"
                  />
                </div>
              ))}
              <Button onClick={handleSaveSlackMessages} className="bg-green-700 hover:bg-green-600 gap-2">
                <Save className="h-4 w-4" /> {slackSaved ? '✓ Saved!' : 'Save Messages'}
              </Button>
            </CardContent>
          </Card>
        )}

        {/* Auto-Assignment Rules — Admin only */}
        {isAdmin && (
          <AutoAssignSettings appSettings={appSettings} allUsers={allUsers} />
        )}

        {/* Add / Manage Users — all admins */}
        {isAdmin && (
          <ManageUsersSection queryClient={queryClient} />
        )}


      </div>
    </div>
  );
}