function MessageTemplatesSection({ appSettings, queryClient }) {
  const defaultRigs = 'Rigs ready for today: {list}';
  const defaultOk = '{name} complete, no issues to report.';
  const defaultIssues = '{name} complete — ⚠️ Issues reported: {notes}';

  const [rigsTemplate, setRigsTemplate] = React.useState('');
  const [summaryOk, setSummaryOk] = React.useState('');
  const [summaryIssues, setSummaryIssues] = React.useState('');
  const [saved, setSaved] = React.useState(false);

  React.useEffect(() => {
    if (!appSettings.length) return;
    setRigsTemplate(appSettings.find(s => s.key === 'rigscheck_template')?.value || defaultRigs);
    setSummaryOk(appSettings.find(s => s.key === 'summary_template_ok')?.value || defaultOk);
    setSummaryIssues(appSettings.find(s => s.key === 'summary_template_issues')?.value || defaultIssues);
  }, [appSettings]);

  const handleSave = async () => {
    const pairs = [
      { key: 'rigscheck_template', value: rigsTemplate, description: 'Rigs check message template' },
      { key: 'summary_template_ok', value: summaryOk, description: 'Shoot summary — no issues template' },
      { key: 'summary_template_issues', value: summaryIssues, description: 'Shoot summary — issues template' },
    ];
    for (const pair of pairs) {
      const existing = appSettings.find(s => s.key === pair.key);
      if (existing) {
        await base44.entities.AppSettings.update(existing.id, { value: pair.value });
      } else {
        await base44.entities.AppSettings.create(pair);
      }
    }
    setSaved(true);
    setTimeout(() => setSaved(false), 2000);
    queryClient.invalidateQueries({ queryKey: ['appSettings'] });
  };

  return (
    <Card className="bg-gray-900 border-gray-800 mb-6">
      <CardHeader className="border-b border-gray-800 pb-4">
        <CardTitle className="text-white flex items-center gap-2">
          <MessageSquare className="h-5 w-5 text-blue-400" /> Message Templates
        </CardTitle>
      </CardHeader>
      <CardContent className="pt-4 space-y-4">
        <p className="text-xs text-gray-500">
          Customise the messages generated by the Rigs Check and Shoot Summary panels.
        </p>

        <div>
          <label className="text-xs text-gray-400 block mb-1">
            Rigs Check message — use <code className="text-blue-400">{'{list}'}</code> for the shoot list
          </label>
          <Input
            value={rigsTemplate}
            onChange={e => setRigsTemplate(e.target.value)}
            placeholder={defaultRigs}
            className="bg-gray-800 border-gray-700 text-white placeholder:text-gray-600 text-sm"
          />
          <p className="text-xs text-gray-600 mt-1">
            Example output: <span className="text-gray-400 italic">Rigs ready for today: Nationals (Data/Fancam), Lightning (Data/Fancam/Sound)</span>
          </p>
        </div>

        <div>
          <label className="text-xs text-gray-400 block mb-1">
            Shoot Summary — no issues — use <code className="text-blue-400">{'{name}'}</code> for shoot name
          </label>
          <Input
            value={summaryOk}
            onChange={e => setSummaryOk(e.target.value)}
            placeholder={defaultOk}
            className="bg-gray-800 border-gray-700 text-white placeholder:text-gray-600 text-sm"
          />
        </div>

        <div>
          <label className="text-xs text-gray-400 block mb-1">
            Shoot Summary — issues reported — use <code className="text-blue-400">{'{name}'}</code> and <code className="text-blue-400">{'{notes}'}</code>
          </label>
          <Input
            value={summaryIssues}
            onChange={e => setSummaryIssues(e.target.value)}
            placeholder={defaultIssues}
            className="bg-gray-800 border-gray-700 text-white placeholder:text-gray-600 text-sm"
          />
        </div>

        <Button onClick={handleSave} className="bg-blue-700 hover:bg-blue-600 gap-2">
          <Save className="h-4 w-4" /> {saved ? '✓ Saved!' : 'Save Templates'}
        </Button>
      </CardContent>
    </Card>
  );
}

function TutorialToggle({ appSettings, settingKey, label, queryClient }) {
  const current = appSettings.find(s => s.key === settingKey)?.value;
  const enabled = current !== 'false';
  const [saving, setSaving] = React.useState(false);

  const toggle = async () => {
    setSaving(true);
    const existing = appSettings.find(s => s.key === settingKey);
    const newVal = enabled ? 'false' : 'true';
    if (existing) {
      await base44.entities.AppSettings.update(existing.id, { value: newVal });
    } else {
      await base44.entities.AppSettings.create({ key: settingKey, value: newVal, description: `Tutorial enabled for ${label}` });
    }
    setSaving(false);
    queryClient.invalidateQueries({ queryKey: ['appSettings'] });
  };

  return (
    <div className="flex items-center justify-between">
      <span className="text-sm text-gray-300">{label}</span>
      <button
        onClick={toggle}
        disabled={saving}
        className={`relative inline-flex h-6 w-11 items-center rounded-full transition-colors ${enabled ? 'bg-blue-600' : 'bg-gray-700'}`}
      >
        <span className={`inline-block h-4 w-4 transform rounded-full bg-white transition-transform ${enabled ? 'translate-x-6' : 'translate-x-1'}`} />
      </button>
    </div>
  );
}

